import json
import os
import glob

def merge_partial_results(folder_path, output_filename="hard_results.json"):
    """
    Search for all _part_x_y_results.json files in the specified folder,
    merge them, sort them by case_id, and output a complete file.
    """
    search_pattern = os.path.join(folder_path, "*_part_*_results.json")
    files_to_merge = glob.glob(search_pattern)
    
    if not files_to_merge:
        print(f"❌ Found no part files with _part_ in {folder_path}!")
        return
        
    print(f"🔍 Found {len(files_to_merge)} part files, merging...")
    
    all_items = []
    for file_path in files_to_merge:
        print(f"   Reading: {os.path.basename(file_path)}")
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
            all_items.extend(data)
            
    # Sort globally by case_id to ensure the output order is exactly the same as a single-process run
    all_items.sort(key=lambda x: x.get("case_id", 0))
    
    output_path = os.path.join(folder_path, output_filename)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(all_items, f, indent=4, ensure_ascii=False)
        
    print("\n" + "="*50)
    print(f"🎉 Merged perfectly! Extracted {len(all_items)} items in total.")
    print(f"📦 Final complete file saved to: {output_path}")
    print("="*50)

if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Merge JSON fragments generated by multi-processing")
    parser.add_argument('--folder', type=str, default='output_metrics/llama3.2-3b/modify/lora', help='Folder path containing the part files')
    parser.add_argument('--output', type=str, default='hard_results.json', help='Final merged file name')
    args = parser.parse_args()
    
    merge_partial_results(args.folder, args.output)